import type { Product } from '@/types';

const BASE_CARE = ['Dry clean only, by a specialist', 'Store flat in the cotton bag provided'];

const MADE_TO_ORDER_DELIVERY = [
  { label: 'Made to order', detail: 'Produced to your measurements in 8–12 weeks, including three fittings.' },
  { label: 'Delivery', detail: 'Insured shipping worldwide. Duties calculated at checkout for international orders.' },
];

const IN_STOCK_DELIVERY = [
  { label: 'Ready to ship', detail: 'Dispatched within 2 working days.' },
  { label: 'Delivery', detail: 'Insured shipping. Duties calculated at checkout for international orders.' },
];

const ENQUIRY_DELIVERY = [
  { label: 'Made to order', detail: 'Timings confirmed at consultation, typically 10–16 weeks.' },
  { label: 'Delivery', detail: 'Collection from the studio or insured shipping worldwide.' },
];

const MADE_TO_MEASURE_RETURNS =
  'Made-to-measure and personalised pieces are non-returnable, as they are cut to your measurements. Ready-to-wear pieces can be returned unworn within 14 days.';

const ENQUIRY_RETURNS =
  'Commissions are non-returnable. Because every piece is cut to order, we confirm measurements in writing before cutting begins.';

/**
 * Builds a product record, filling in the care, delivery and returns copy that
 * is the same for every piece from a given kind of production.
 */
function mk(
  p: Omit<Product, 'care' | 'delivery' | 'returns'> &
    Partial<Pick<Product, 'care' | 'delivery' | 'returns'>>,
): Product {
  const isEnquiry = p.availability === 'enquire' || p.price === null;
  return {
    care: BASE_CARE,
    delivery: isEnquiry ? ENQUIRY_DELIVERY : p.availability === 'made-to-order' ? MADE_TO_ORDER_DELIVERY : IN_STOCK_DELIVERY,
    returns: isEnquiry ? ENQUIRY_RETURNS : MADE_TO_MEASURE_RETURNS,
    ...p,
  };
}

